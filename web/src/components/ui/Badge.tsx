/** Small status and classification chips. */

import type { ReactNode } from "react";

import { cn } from "@/lib/cn";
import { riskPresentation, riskLevelFromScore } from "@/lib/risk";
import type { CameraStatus, DataOrigin, Determination, JobStatus, RiskLevel } from "@shared/domain";

type Tone = "neutral" | "accent" | "info" | "low" | "moderate" | "high" | "critical" | "offline";

const TONE_CLASS: Record<Tone, string> = {
  neutral: "border-line-strong bg-surface-raised text-ink-muted",
  accent: "border-accent-line bg-accent-dim text-accent",
  info: "border-info/40 bg-info-dim text-info",
  low: "border-risk-low/40 bg-risk-low-dim text-risk-low",
  moderate: "border-risk-moderate/40 bg-risk-moderate-dim text-risk-moderate",
  high: "border-risk-high/40 bg-risk-high-dim text-risk-high",
  critical: "border-risk-critical/40 bg-risk-critical-dim text-risk-critical",
  offline: "border-offline/40 bg-offline-dim text-offline",
};

interface BadgeProps {
  children: ReactNode;
  tone?: Tone;
  className?: string;
  title?: string;
}

export function Badge({ children, tone = "neutral", className, title }: BadgeProps) {
  return (
    <span
      title={title}
      className={cn(
        "inline-flex items-center gap-1 rounded-sm border px-1.5 py-0.5 text-2xs font-semibold tracking-wide whitespace-nowrap uppercase",
        TONE_CLASS[tone],
        className,
      )}
    >
      {children}
    </span>
  );
}

const RISK_TONE: Record<RiskLevel, Tone> = {
  LOW: "low",
  MODERATE: "moderate",
  HIGH: "high",
  CRITICAL: "critical",
};

interface RiskBadgeProps {
  /** Provide either a level or a 0-100 score. */
  level?: RiskLevel;
  score?: number;
  /** Appends the numeric score, e.g. "High 68". */
  showScore?: boolean;
  className?: string;
}

/** Risk level chip. Always carries the text label, never colour alone. */
export function RiskBadge({ level, score, showScore, className }: RiskBadgeProps) {
  const resolved = level ?? (score === undefined ? "LOW" : riskLevelFromScore(score));
  const { label } = riskPresentation(resolved);
  return (
    <Badge tone={RISK_TONE[resolved]} className={className}>
      {label}
      {showScore && score !== undefined ? (
        <span className="opacity-70 tabular-nums">{Math.round(score)}</span>
      ) : null}
    </Badge>
  );
}

const CAMERA_TONE: Record<CameraStatus, Tone> = {
  ONLINE: "low",
  OFFLINE: "offline",
  PROCESSING: "info",
  ALERT: "critical",
};

export function CameraStatusBadge({ status }: { status: CameraStatus }) {
  return <Badge tone={CAMERA_TONE[status]}>{status.toLowerCase()}</Badge>;
}

const JOB_TONE: Record<JobStatus, Tone> = {
  QUEUED: "neutral",
  PROCESSING: "info",
  COMPLETED: "low",
  FAILED: "critical",
  CANCELLED: "offline",
};

export function JobStatusBadge({ status }: { status: JobStatus }) {
  return <Badge tone={JOB_TONE[status]}>{status.toLowerCase()}</Badge>;
}

/**
 * Provenance chip. `DEMO` and `ESTIMATED` are always shown; `MEASURED` renders
 * nothing, so the absence of a chip means the value was actually measured.
 * This is the visual half of the data-honesty contract.
 */
export function OriginBadge({ origin, className }: { origin: DataOrigin; className?: string }) {
  if (origin === "MEASURED") return null;
  if (origin === "DEMO") {
    return (
      <Badge tone="accent" className={className} title="Synthetic record generated by demo mode.">
        Demo data
      </Badge>
    );
  }
  return (
    <Badge
      tone="neutral"
      className={className}
      title="Derived from a model or geometric estimate, not a direct measurement."
    >
      Estimated
    </Badge>
  );
}

/**
 * Tri-state visual check result. `UNABLE_TO_DETERMINE` is rendered plainly
 * rather than being collapsed into a negative.
 */
export function DeterminationBadge({ value }: { value: Determination }) {
  if (value === "DETECTED") return <Badge tone="low">Detected</Badge>;
  if (value === "NOT_DETECTED") return <Badge tone="critical">Not detected</Badge>;
  return (
    <Badge tone="offline" title="Visual evidence was insufficient for a determination.">
      Unable to determine
    </Badge>
  );
}
